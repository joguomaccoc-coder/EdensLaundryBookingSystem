    private void loadBooking(int bookingId) {

        String url = "jdbc:mysql://localhost:3306/laundry_booking_system";
        String user = "root";
        String password = "";

        String sql = "SELECT s.service_name, b.quantity, " +
                     "b.booking_date, b.total_price, b.note " +
                     "FROM tbl_bookings b " +
                     "JOIN tbl_services s ON b.service_id = s.service_id " +
                     "WHERE b.booking_id = ?";

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();

        model.setRowCount(0);
        model.setColumnIdentifiers(new String[]{"Booking Details", "Information Inputted"});

        try (Connection conn = DriverManager.getConnection(url, user, password);
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setInt(1, bookingId);

            try (ResultSet rs = ps.executeQuery()) {

                if (rs.next()) {
                    model.addRow(new Object[]{
                        "Laundry Service",
                        rs.getString("service_name")
                    });

                    model.addRow(new Object[]{
                        "Laundry Weight (kg) / Quantity",
                        rs.getString("quantity") + " kg"
                    });

                    model.addRow(new Object[]{
                        "Booking Date",
                        rs.getDate("booking_date")
                    });

                    model.addRow(new Object[]{
                        "Price / Total Amount",
                        "₱" + String.format("%.2f", rs.getDouble("total_price"))
                    });

                    model.addRow(new Object[]{
                        "Note",
                        (rs.getString("note") == null || rs.getString("note").trim().isEmpty()) 
                            ? "None" 
                            : rs.getString("note")
                    });

                    if (jTable1.getColumnModel().getColumnCount() > 0) {
                        jTable1.getColumnModel().getColumn(0).setPreferredWidth(220);
                        jTable1.getColumnModel().getColumn(1).setPreferredWidth(320);
                    }

                } else {
                    JOptionPane.showMessageDialog(this, "Booking not found.");
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
            e.printStackTrace();
        }
    }


    

