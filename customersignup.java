    private void btnCreateAccountActionPerformed(java.awt.event.ActionEvent evt) {                                                 
                                                     
    // 1. Read input values from the form
    String enteredEmail = txtEmail.getText().trim();
    String enteredUsername = txtUsername.getText().trim();
    String enteredContact = txtContact.getText().trim();
    String enteredPassword = new String(txtPassword.getPassword());

    String enteredLastName = txtLastName.getText().trim();
    String enteredFirstName = txtFirstName.getText().trim();
    String enteredMI = txtMiddleInitial.getText().trim();

    // 2. Validate required fields
    if (enteredUsername.isEmpty() || enteredPassword.isEmpty() || enteredFirstName.isEmpty() || enteredLastName.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please fill in all required fields (*).",
            "Sign Up Error",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }
    
    // Check if email ends with @gmail.com
    if (!enteredEmail.toLowerCase().endsWith("@gmail.com")) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter a valid Gmail address ending with @gmail.com",
            "Invalid Email Address",
            JOptionPane.ERROR_MESSAGE
        );
        txtEmail.requestFocus();
        return;
    }

    // 3. Strict 11-Digit Contact Number Validation
    if (!enteredContact.matches("^09\\d{9}$")) {
        JOptionPane.showMessageDialog(
            this,
            "Contact number must be exactly 11 digits (e.g., 09123456789).",
            "Invalid Contact Number",
            JOptionPane.ERROR_MESSAGE
        );
        txtContact.requestFocus();
        return;
    }

    // 4. MySQL Connection Details
    String url = "jdbc:mysql://localhost:3306/laundry_booking_system";
    String dbUsername = "root";
    String dbPassword = "";

    // Queries
    String checkUserSql = "SELECT user_id FROM tbl_users WHERE username = ? OR email = ?";
    String insertSql = "INSERT INTO tbl_users (role_id, username, email, first_name, last_name, middle_initial, contact_no, password) "
                     + "VALUES (?, ?, ?, ?, ?, ?, ?, ?)";

    try (Connection conn = DriverManager.getConnection(url, dbUsername, dbPassword)) {

        // 5. Check if Username or Email already exists
        try (PreparedStatement checkPst = conn.prepareStatement(checkUserSql)) {
            checkPst.setString(1, enteredUsername);
            checkPst.setString(2, enteredEmail);

            try (ResultSet rs = checkPst.executeQuery()) {
                if (rs.next()) {
                    JOptionPane.showMessageDialog(
                        this,
                        "This user already exists! (Username or Email is already registered)",
                        "Account Duplicate",
                        JOptionPane.WARNING_MESSAGE
                    );
                    return;
                }
            }
        }

        // 6. Insert new user if no duplicate was found
        try (PreparedStatement pst = conn.prepareStatement(insertSql)) {
            pst.setInt(1, 2); // 2 = Customer Role
            pst.setString(2, enteredUsername);
            pst.setString(3, enteredEmail);
            pst.setString(4, enteredFirstName);
            pst.setString(5, enteredLastName);
            pst.setString(6, enteredMI);
            pst.setString(7, enteredContact);
            pst.setString(8, enteredPassword);

            int rowsInserted = pst.executeUpdate();

            if (rowsInserted > 0) {
                JOptionPane.showMessageDialog(
                    this,
                    "Account Created Successfully!",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE
                );

                homeadmin home = new homeadmin();
                home.setVisible(true);
                this.dispose();
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Error creating account:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
        e.printStackTrace();
    
}  // TODO add your handling code here:
    }                                                

