    private void loadDashboardData() {
    String url = "jdbc:mysql://localhost:3306/laundry_booking_system";
    String dbUser = "root";
    String dbPassword = "";

    // SQL Queries
    String totalBookingsSql = "SELECT COUNT(*) FROM tbl_bookings";
    String totalSalesSql = "SELECT IFNULL(SUM(total_price), 0) FROM tbl_bookings";
    String completedOrdersSql = "SELECT COUNT(*) FROM tbl_bookings WHERE booking_status = 'Completed'";
    String pendingOrdersSql = "SELECT COUNT(*) FROM tbl_bookings WHERE booking_status = 'Pending'";

    String recentOrdersSql = "SELECT b.booking_id, u.full_name, s.service_name, b.quantity, " +
                             "b.total_price, b.booking_date, b.booking_status " +
                             "FROM tbl_bookings b " +
                             "JOIN tbl_users u ON b.user_id = u.user_id " +
                             "JOIN tbl_services s ON b.service_id = s.service_id " +
                             "ORDER BY b.booking_id DESC LIMIT 10";

    try (Connection conn = DriverManager.getConnection(url, dbUser, dbPassword)) {

        // 1. Total Bookings
        try (PreparedStatement ps = conn.prepareStatement(totalBookingsSql);
             ResultSet rs = ps.executeQuery()) {
            if (rs.next()) {
                jLabel50.setText(String.valueOf(rs.getInt(1)));
            }
        }

        // 2. Total Sales
        try (PreparedStatement ps = conn.prepareStatement(totalSalesSql);
             ResultSet rs = ps.executeQuery()) {
            if (rs.next()) {
                double totalSales = rs.getDouble(1);
                jLabel51.setText("₱" + String.format("%.2f", totalSales));
            }
        }

        // 3. Completed Orders
        try (PreparedStatement ps = conn.prepareStatement(completedOrdersSql);
             ResultSet rs = ps.executeQuery()) {
            if (rs.next()) {
                jLabel53.setText(String.valueOf(rs.getInt(1)));
            }
        }

        // 4. Pending Orders
        try (PreparedStatement ps = conn.prepareStatement(pendingOrdersSql);
             ResultSet rs = ps.executeQuery()) {
            if (rs.next()) {
                jLabel52.setText(String.valueOf(rs.getInt(1)));
            }
        }

        // 5. Populate Table
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        try (PreparedStatement ps = conn.prepareStatement(recentOrdersSql);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("booking_id"),
                    rs.getString("full_name"),
                    rs.getString("service_name"),
                    rs.getString("quantity") + " kg",
                    "₱" + String.format("%.2f", rs.getDouble("total_price")),
                    rs.getDate("booking_date"),
                    rs.getString("booking_status")
                });
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Database Connection Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        e.printStackTrace();
    }
}
    
