    private void loadUserBookings() {
    int loggedInUserId = UserSession.userId;

    if (loggedInUserId == -1) {
        JOptionPane.showMessageDialog(this, "Please log in first.", "Session Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    String url = "jdbc:mysql://localhost:3306/laundry_booking_system";
    String user = "root";
    String password = "";

    String sql = "SELECT b.booking_id, s.service_name, b.booking_date, b.quantity, " +
                 "b.total_price, b.booking_status " +
                 "FROM tbl_bookings b " +
                 "JOIN tbl_services s ON b.service_id = s.service_id " +
                 "WHERE b.user_id = ? " +
                 "ORDER BY b.booking_id DESC";

    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);

    try (Connection conn = DriverManager.getConnection(url, user, password);
         PreparedStatement ps = conn.prepareStatement(sql)) {

        ps.setInt(1, loggedInUserId);

        try (ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("booking_id"),
                    rs.getString("service_name"),
                    rs.getDate("booking_date"),
                    rs.getString("quantity") + " kg",
                    "₱" + String.format("%.2f", rs.getDouble("total_price")),
                    rs.getString("booking_status"),
                    "View / Cancel"
                });
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
        e.printStackTrace();
    }

}
